/*
9. Staff Sales Activity
----------------------------
Find all staff members who have handled more than 50 orders. 
Display their full name (concatenated), their store name, and the total count of orders they 
processed. Sort the output alphabetically by store name, and then by the order count in 
descending order.
*/

SELECT 
	CONCAT(ss.first_name, ' ', ss.last_name) AS staff_name,
	sst.store_name,
	COUNT(so.order_id) AS total_orders
FROM sales.staffs ss
JOIN sales.orders so
ON ss.staff_id = so.staff_id
JOIN sales.stores sst
ON so.store_id = sst.store_id
GROUP BY CONCAT(ss.first_name, ' ', ss.last_name), sst.store_name
HAVING COUNT(so.order_id) > 50 
ORDER BY store_name ASC, total_orders DESC

/*
10. Discount Impact Analysis 
-------------------------------
Analyze the revenue lost to discounts across different 
product categories. For every product category, calculate:
• The total potential revenue (if there were no discounts).
• The actual revenue (applying the discount column).
• The total dollar amount of discounts given. Use GROUP BY and HAVING to only 
show categories where the total discount amount given exceeds $5,000.
*/

SELECT 
pc.category_name,
SUM(soi.list_price* soi.quantity) as potential_revenue,
SUM(soi.list_price*soi.quantity*(1-soi.discount)) as actual_revenue,
SUM(soi.discount * soi.list_price* soi.quantity) as discount_given
FROM sales.order_items soi
JOIN production.products pp
ON soi.product_id = pp.product_id 
JOIN production.categories pc
ON pp.category_id = pc.category_id
GROUP BY pc.category_name
HAVING SUM(soi.discount * soi.list_price* soi.quantity) > 5000 ;


