/*
1. Brand Listing
-----------------------
Write a query to list all product names along with their corresponding 
brand names. Sort the results alphabetically by brand name.
*/

SELECT 
pp.product_name,pb.brand_name
FROM production.products pp
JOIN production.brands pb
ON pp.brand_id = pb.brand_id
ORDER BY pb.brand_name;

/*
2. Store Contact List
-------------------------
Retrieve a list of all staff members, including their first and last 
names, and the store name where they work.
*/

SELECT 
	CONCAT(staff.first_name, ' ', staff.last_name) as staff_name,
	store.store_name
FROM sales.staffs staff 
JOIN sales.stores store
ON staff.store_id = store.store_id;


/* 
3. Customer Order History 
--------------------------
Show all orders (order ID and order date) along with the 
customer's full name (first and last) who placed them. Order the results by the order date 
in descending order (most recent first)
*/
SELECT 
so.order_id, so.order_date,
CONCAT(sc.first_name, ' ', sc.last_name) as customer_name
FROM sales.orders so
JOIN sales.customers sc
ON sc.customer_id = so.customer_id
ORDER BY so.order_date DESC;



/*
4. Category Stock Levels Calculate the total quantity of products in stock for each 
category name. Group the results by category and use a HAVING clause to only show 
categories that have more than 500 items in total stock.
*/

SELECT pc.category_name, SUM(ps.quantity) as total_quantity 
FROM production.categories pc
JOIN production.products pp
ON pc.category_id = pp.category_id
JOIN production.stocks ps
ON pp.product_id = ps.product_id
GROUP BY pc.category_name
HAVING SUM(ps.quantity) > 500;



/*
5. Sales Performance by Store
---------------------------------
Find the total sales amount (calculated as quantity * 
list_price) generated by each store. Display the store name and the total sales revenue, 
ordered from the highest revenue to the lowest.

*/
SELECT 
ss.store_name, SUM(soi.quantity*soi.list_price) as total_sales_revenue
FROM sales.stores ss
JOIN sales.orders so
ON ss.store_id = so.store_id
JOIN sales.order_items soi
ON so.order_id = soi.order_id
GROUP BY ss.store_name
ORDER BY total_sales_revenue DESC;

/*
6. . Product Pricing Tiers 
---------------------------------
List all products, their category names, and their list prices. Use a 
CASE statement to create a new column called 'Price_Segment' that labels them as:
• 'Budget' (if price is under $500)
• 'Mid-Range' (if price is between $500 and $2000)
• 'Premium' (if price is over $2000)
*/

SELECT 
pp.product_name, pc.category_name, list_price, 
	CASE
		WHEN list_price <500 THEN 'Budget' 
		WHEN list_price >=500 and list_price<=2000 THEN 'Mid-Range'
		WHEN list_price > 2000 THEN 'Premium'
	END AS Price_Segment
FROM production.products pp
JOIN production.categories pc
	ON pp.category_id= pc.category_id;

/*
7. Bulk Order Summary For each order
------------------------------------
Find the total number of distinct products ordered. 
Display the Order ID and the Product Count, but only for orders that contain more than 3 
different products.
*/

SELECT 
soi.order_id,
COUNT( DISTINCT soi.product_id) AS total_number_of_products
FROM sales.order_items soi
JOIN production.products pp
ON soi.product_id = pp.product_id
GROUP BY soi.order_id
HAVING COUNT( DISTINCT soi.product_id) > 3;

/*
8. Brand Performance Analysis
---------------------------------
Identify the brands that have sold more than 100 units in 
total. Your output should include the Brand Name, the total Quantity Sold, and a CASE
statement that flags the brand as "Top Performer" if sales exceed 500 units, and 
"Standard" otherwise. (Hint: Join brands, products, and order_items).
*/


SELECT 
brands.brand_name, SUM (order_items.quantity) AS total_sold,
CASE 
	WHEN SUM (order_items.quantity) > 500 THEN 'Top Performer' ELSE 'Standard' 
END AS status
FROM production.brands brands
JOIN production.products products
	ON brands.brand_id = products.brand_id
JOIN sales.order_items order_items
	ON order_items.product_id = products.product_id
GROUP BY brands.brand_name
HAVING SUM (order_items.quantity) > 100 ;

